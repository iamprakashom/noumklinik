export const DEFAULT_COUNTRY = COUNTRIES[0];

const SORTED_COUNTRIES_DESC = [...COUNTRIES].sort((a, b) => {
  if (b.code.length !== a.code.length) {
    return b.code.length - a.code.length;
  }
  if (a.iso === "IN") return -1;
  if (b.iso === "IN") return 1;
  if (a.iso === "US") return -1;
  if (b.iso === "US") return 1;
  if (a.iso === "GB") return -1;
  if (b.iso === "GB") return 1;
  return 0;
});

export function splitDefault(val: string | null | undefined): {
  iso: string;
  code: string;
  value: string;
} {
  if (!val) return { iso: "IN", code: "91", value: "" };
  const s = String(val).trim();
  const digits = s.replace(/\D/g, "");
  if (s.startsWith("+") && digits.length > 0) {
    for (const c of SORTED_COUNTRIES_DESC) {
      if (digits.startsWith(c.code)) {
        return {
          iso: c.iso,
          code: c.code,
          value: digits.slice(c.code.length),
        };
      }
    }
  }
  return { iso: "IN", code: "91", value: digits };
}
